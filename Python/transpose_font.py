def transpose_char(rm):
    """Transpose one 8x16 character from row-major to column-major."""
    cm = [0] * 16
    # Upper half (rows 0-7) → columns 0-7 of upper page
    for col in range(8):
        byte_val = 0
        for row in range(8):
            if rm[row] & (0x80 >> col):
                byte_val |= (0x80 >> row)
        cm[col] = byte_val
    # Lower half (rows 8-15) → columns 0-7 of lower page
    for col in range(8):
        byte_val = 0
        for row in range(8):
            if rm[8 + row] & (0x80 >> col):
                byte_val |= (0x80 >> row)
        cm[8 + col] = byte_val
    return cm

