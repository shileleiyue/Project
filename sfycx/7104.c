// 题目描述
// 约瑟夫问题：有ｎ只猴子，按顺时针方向围成一圈选大王（编号从１到ｎ），从第１号开始报数，一直数到ｍ，数到ｍ的猴子退出圈外，剩下的猴子再接着从1 开始报数。就这样，直到圈内只剩下一只猴子时，这个猴子就是猴王，编程求输入ｎ，ｍ后，输出最后猴王的编号。
// 输入
// 每行是用空格分开的两个整数，第一个是 n，第二个是m ( 0 < m, n < 300) 。最后一行是：0 0 。
// 输出
// 对于每行输入数据（最后一行除外)，输出数据也是一行，即最后猴王的编号。
// 样例输入 复制
// 6 2
// 12 4
// 8 3
// 0 0
// 样例输出 复制
// 5
// 1
// 7
#include <stdio.h>

int josephus(int n, int m) {
    int winner = 0; // 当只有1只猴子时，编号为0（偏移量）
    for (int i = 2; i <= n; i++) {
        winner = (winner + m) % i;
    }
    return winner + 1; // 转换为1-based编号
}

int main() {
    int n, m;
    while (scanf("%d %d", &n, &m) == 2) {
        if (n == 0 && m == 0) break;
        printf("%d\n", josephus(n, m));
    }
    return 0;
}